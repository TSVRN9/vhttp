#[test]
fn gcm_matches_rustcrypto() {
    use aes_gcm::aead::{Aead, KeyInit, Payload};
    let pts = (0..=300usize).flat_map(|p| [(p, 0), (p, 20)]);
    let aads = (0..=300usize).flat_map(|a| [(0, a), (17, a)]);
    for (pl, al) in pts.chain(aads) {
        let l = pl + al;
        let k: [u8; 16] = core::array::from_fn(|j| (l * 31 + j * 7 + 1) as u8);
        let n: [u8; 12] = core::array::from_fn(|j| (l * 13 + j * 5 + 9) as u8);
        let pt: Vec<u8> = (0..pl).map(|j| (j * 3 + l) as u8).collect();
        let aad: Vec<u8> = (0..al).map(|j| (j * 11 + 5) as u8).collect();
        let rc = aes_gcm::Aes128Gcm::new(&k.into());
        let rc_open = |ct: &[u8]| rc.decrypt(&n.into(), Payload { msg: ct, aad: &aad }).ok();
        let ct = aes128_gcm_seal(&k, &n, &aad, &pt);
        assert_eq!(ct, rc.encrypt(&n.into(), Payload { msg: &pt, aad: &aad }).unwrap(), "pt {pl} aad {al}");
        assert_eq!(aes128_gcm_open(&k, &n, &aad, &ct), Some(pt.clone()), "pt {pl} aad {al}");
        let mut bad = ct.clone();
        bad[pl + l % 16] ^= 1 << (l % 8);
        assert_eq!((aes128_gcm_open(&k, &n, &aad, &bad), rc_open(&bad)), (None, None), "tag: pt {pl} aad {al}");
        if pl > 0 {
            let mut bad = ct.clone();
            bad[0] ^= 1;
            assert_eq!((aes128_gcm_open(&k, &n, &aad, &bad), rc_open(&bad)), (None, None), "ct: pt {pl} aad {al}");
        }
    }
}

#[test]
fn rfc9001_initial_aead() {
    // RFC 9001 A.3: server Initial, nonce = iv xor packet number 1, aad = the unprotected header
    let (k, n, aad, pt) = (
        h("cf3a5331653c364c88f0f379b6067e37"),
        h("0ac1493ca1905853b0bba03f"),
        h("c1000000010008f067a5502a4262b50040750001"),
        h(A3_PT),
    );
    let r = aes128_gcm_seal(&k, &n, &aad, &pt);
    assert_eq!(r, h(A3_SEAL));
    assert_eq!(aes128_gcm_open(&k, &n, &aad, &r), Some(pt));
    // RFC 9001 A.2: client Initial, packet number 2, the CRYPTO frame padded to 1162 bytes;
    // the protected payload is checked by its SHA-256
    let (k, n, aad) = (
        h("1f369613dd76d5467730efcbe3b1a22d"),
        h("fa044b2f42a3fd3b46fb255e"),
        h("c300000001088394c8f03e5157080000449e00000002"),
    );
    let mut pt = h(A2_CRYPTO);
    pt.resize(1162, 0);
    let r = aes128_gcm_seal(&k, &n, &aad, &pt);
    assert_eq!(
        crypto::sha256::sha256(&r).to_vec(),
        h("b920e67ea7fdfe77e9f2c3a24d75c04afed30c24ec84d5bcd5464f634657e49f")
    );
    assert_eq!(aes128_gcm_open(&k, &n, &aad, &r), Some(pt));
}

#[test]
fn gcm_64kib() {
    use aes_gcm::aead::{Aead, KeyInit, Payload};
    use std::time::Instant;
    let (k, n, aad) = ([7u8; 16], [9u8; 12], [0x5au8; 20]);
    let pt: Vec<u8> = (0..65536usize).map(|i| (i * 7) as u8).collect();
    let rc = aes_gcm::Aes128Gcm::new(&k.into());
    let t = Instant::now();
    let ct = aes128_gcm_seal(&k, &n, &aad, &pt);
    let seal = t.elapsed();
    assert_eq!(ct, rc.encrypt(&n.into(), Payload { msg: &pt, aad: &aad }).unwrap());
    let t = Instant::now();
    let back = aes128_gcm_open(&k, &n, &aad, &ct);
    let open = t.elapsed();
    assert_eq!(back, Some(pt.clone()));
    // GHASH only: 64 KiB of aad, no plaintext
    let t = Instant::now();
    let tag = aes128_gcm_seal(&k, &n, &pt, &[]);
    let ghash = t.elapsed();
    assert_eq!(tag, rc.encrypt(&n.into(), Payload { msg: &[], aad: &pt }).unwrap());
    // 4096 single blocks, each with its own key schedule
    let t = Instant::now();
    for b in pt.chunks(16) {
        std::hint::black_box(aes128_encrypt_block(&k, b));
    }
    let ecb = t.elapsed();
    let us = |d: std::time::Duration| d.as_secs_f64() * 1e6 / 4096.0;
    println!(
        "gcm_64kib: seal {seal:?}, open {open:?}; per 16-byte block: seal {:.3} us, GHASH {:.3} us, \
         AES {:.3} us, aes128_encrypt_block {:.3} us",
        us(seal),
        us(ghash),
        us(seal) - us(ghash),
        us(ecb)
    );
}
