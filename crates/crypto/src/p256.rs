    fn fe_inv_roundtrip() {
        let xs: [[u64; 4]; 8] = [
            [1, 0, 0, 0],
            [2, 0, 0, 0],
            [u64::MAX, 0, 0, 0],
            ONE_MONT,
            THREE_MONT,
            B_MONT,
            R2_P,
            [0xfffffffffffffffe, 0x00000000ffffffff, 0, 0xffffffff00000001],
        ];
        for x in xs {
            assert_eq!(fe_mul(x, fe_inv(x)), ONE_MONT, "x = {:x?}", x);
        }
    }
