    fn scalar(k: u64) -> [u8; 32] {
        let mut s = [0u8; 32];
        s[24..].copy_from_slice(&k.to_be_bytes());
        s
    }

    #[test]
    fn group_add_vectors() {
        for (i, (x, y)) in ADD_TEST_VECTORS.iter().enumerate() {
            let k = i as u64 + 1;
            let r = scalar_mult_ct(&scalar(k), &g_point());
            assert_eq!(r.inf, 0, "k = {}", k);
            assert_eq!(&fe_to_be(&r.x), x, "x, k = {}", k);
            assert_eq!(&fe_to_be(&r.y), y, "y, k = {}", k);
        }
    }

    #[test]
    fn group_mul_vectors() {
        for (k, x, y) in MUL_TEST_VECTORS.iter() {
            let r = scalar_mult_ct(k, &g_point());
            assert_eq!(r.inf, 0, "k = {:02x?}", k);
            assert_eq!(&fe_to_be(&r.x), x, "x, k = {:02x?}", k);
            assert_eq!(&fe_to_be(&r.y), y, "y, k = {:02x?}", k);
        }
    }

    #[test]
    fn n_minus_1_is_minus_g() {
        let mut k = P256_N;
        k[31] -= 1;
        let g = g_point();
        let r = scalar_mult_ct(&k, &g);
        assert_eq!(r.inf, 0);
        assert_eq!(fe_to_be(&r.x), P256_GX);
        // p - Gy, as 0 - Gy in GF(p).
        assert_eq!(fe_to_be(&r.y), fe_to_be(&fe_sub([0; 4], g.y)));
        assert_ne!(fe_to_be(&r.y), P256_GY);
    }

    #[test]
    fn zero_is_infinity() {
        assert_eq!(scalar_mult_ct(&[0u8; 32], &g_point()).inf, 1);
    }

    #[test]
    fn point_add_ladder() {
        // R = O; R = G + R, i.e. the spec's scalar_mult(k, G) = point_add(G, scalar_mult(k - 1, G)).
        let mut r = AffPt { x: [0; 4], y: [0; 4], inf: 1 };
        for (k, (x, y)) in ADD_TEST_VECTORS.iter().enumerate() {
            r = point_add_ct(&g_point(), &r);
            assert_eq!(r.inf, 0, "k = {}", k + 1);
            assert_eq!(&fe_to_be(&r.x), x, "x, k = {}", k + 1);
            assert_eq!(&fe_to_be(&r.y), y, "y, k = {}", k + 1);
        }
    }

