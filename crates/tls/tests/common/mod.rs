/// Decodes a hex string, ignoring whitespace.
pub fn hex(s: &str) -> Vec<u8> {
    let d: Vec<u8> = s.bytes().filter(|c| !c.is_ascii_whitespace()).collect();
    assert!(d.len() % 2 == 0, "odd hex length");
    d.chunks(2)
        .map(|p| u8::from_str_radix(std::str::from_utf8(p).unwrap(), 16).unwrap())
        .collect()
}

fn be16(x: usize) -> [u8; 2] {
    [(x >> 8) as u8, x as u8]
}

/// A ClientHello message split into the bytes between the handshake header and the
/// extension block, and the extensions in wire order.
pub fn split_ch(msg: &[u8]) -> (Vec<u8>, Vec<(u16, Vec<u8>)>) {
    let mut i = 4 + 2 + 32;
    i += 1 + msg[i] as usize;
    i += 2 + (((msg[i] as usize) << 8) | msg[i + 1] as usize);
    i += 1 + msg[i] as usize;
    let head = msg[4..i].to_vec();
    let end = i + 2 + (((msg[i] as usize) << 8) | msg[i + 1] as usize);
    assert_eq!(end, msg.len());
    let mut exts = Vec::new();
    let mut j = i + 2;
    while j < end {
        let ty = ((msg[j] as u16) << 8) | msg[j + 1] as u16;
        let n = ((msg[j + 2] as usize) << 8) | msg[j + 3] as usize;
        exts.push((ty, msg[j + 4..j + 4 + n].to_vec()));
        j += 4 + n;
    }
    (head, exts)
}

/// The full ClientHello message: header, `head`, then the extension block of `exts`.
pub fn join_ch(head: &[u8], exts: &[(u16, Vec<u8>)]) -> Vec<u8> {
    let mut block = Vec::new();
    for (ty, d) in exts {
        block.extend(be16(*ty as usize));
        block.extend(be16(d.len()));
        block.extend(d);
    }
    let n = head.len() + 2 + block.len();
    let mut m = vec![1, (n >> 16) as u8, (n >> 8) as u8, n as u8];
    m.extend(head);
    m.extend(be16(block.len()));
    m.extend(block);
    m
}

/// ClientHello fields up to the extension block, with A.2's random.
pub fn head(version: u16, session_id: &[u8], suites: &[u16], comp: &[u8]) -> Vec<u8> {
    let mut h = be16(version as usize).to_vec();
    h.extend_from_slice(&A2_CH[6..38]);
    h.push(session_id.len() as u8);
    h.extend_from_slice(session_id);
    h.extend(be16(2 * suites.len()));
    for s in suites {
        h.extend(be16(*s as usize));
    }
    h.push(comp.len() as u8);
    h.extend_from_slice(comp);
    h
}

