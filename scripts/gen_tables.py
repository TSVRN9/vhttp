#!/usr/bin/env python3
"""Generate crates/h3/src/qpack/{static_table,huffman_table}.rs from the RFC appendix texts in
crates/h3/rfc/. Stdlib only, deterministic. Independently re-checked by crates/h3/tests/static_table.rs
(own Rust parser over the same text). Run: python3 scripts/gen_tables.py"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RFC = ROOT / "crates/h3/rfc"
OUT = ROOT / "crates/h3/src/qpack"
HEADER = "// @generated by scripts/gen_tables.py from {src}. DO NOT EDIT; rerun the script.\n"


def join_wrapped(pieces):
    """RFC line-wrapping: no space after a trailing '-' or '/', otherwise one space."""
    s = ""
    for p in pieces:
        if s:
            s += "" if s[-1] in "-/" else " "
        s += p
    return s


def parse_static(text):
    rows, cur = [], None
    for line in text.splitlines():
        if not line.lstrip().startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != 3 or cells[0] == "Index":
            continue
        if cells[0]:
            cur = [int(cells[0]), [cells[1]], [cells[2]]]
            rows.append(cur)
        else:
            assert cur is not None
            for k in (1, 2):
                if cells[k]:
                    cur[k].append(cells[k])
    out = [(i, join_wrapped(n), join_wrapped(v)) for i, n, v in rows]
    assert [r[0] for r in out] == list(range(99)), "static table must be indices 0..98"
    return out


def parse_huff(text):
    rows = {}
    for line in text.splitlines():
        m = re.search(r"\(\s*(\d+)\)\s+\|([01|]+)\s+([0-9a-f]+)\s+\[\s*(\d+)\]\s*$", line)
        if not m:
            continue
        sym, bits, hx, ln = int(m[1]), m[2].replace("|", ""), int(m[3], 16), int(m[4])
        assert sym not in rows and len(bits) == ln and int(bits, 2) == hx, line
        rows[sym] = (hx, ln)
    assert sorted(rows) == list(range(257))
    return rows


def seq(s):
    b = s.encode("ascii")
    return "seq![" + ", ".join(f"{x}u8" for x in b) + "]"


def arr(s):
    b = s.encode("ascii")
    return "&[" + ", ".join(f"{x}u8" for x in b) + "]"


STATIC_TAIL = '''
pub open spec fn spec_name_is(j: nat, name: Seq<u8>) -> bool {
    spec_static_entry(j) matches Some((n, _)) && n == name
}

/// Index of the first entry whose name and value both match (`Exact`), else of the first entry
/// whose name matches (`Name`), else `None`. Lowest index wins ties.
pub fn find_static(name: &[u8], value: &[u8]) -> (r: StaticMatch)
    ensures
        match r {
            StaticMatch::Exact(i) => {
                &&& i < STATIC_TABLE_LEN
                &&& spec_static_entry(i as nat) == Some((name@, value@))
                &&& forall|j: nat| j < i ==> spec_static_entry(j) != Some((name@, value@))
            },
            StaticMatch::Name(i) => {
                &&& i < STATIC_TABLE_LEN
                &&& spec_name_is(i as nat, name@)
                &&& forall|j: nat| j < STATIC_TABLE_LEN ==> spec_static_entry(j) != Some((name@, value@))
                &&& forall|j: nat| j < i ==> !spec_name_is(j, name@)
            },
            StaticMatch::None => forall|j: nat|
                j < STATIC_TABLE_LEN ==> !spec_name_is(j, name@),
        },
{
    let mut first_name: Option<u64> = None;
    let mut i: u64 = 0;
    // ponytail: linear scan over 99 entries; switch to a name-indexed match if profiling shows it
    while i < 99
        invariant
            i <= 99,
            forall|j: nat| j < i ==> spec_static_entry(j) != Some((name@, value@)),
            match first_name {
                Some(k) => {
                    &&& k < i
                    &&& spec_name_is(k as nat, name@)
                    &&& forall|j: nat| j < k ==> !spec_name_is(j, name@)
                },
                None => forall|j: nat| j < i ==> !spec_name_is(j, name@),
            },
        decreases 99 - i,
    {
        match static_entry(i) {
            Some((n, v)) => {
                if bytes_eq(n, name) {
                    if bytes_eq(v, value) {
                        return StaticMatch::Exact(i);
                    }
                    if first_name.is_none() {
                        first_name = Some(i);
                    }
                }
            },
            None => {},
        }
        i += 1;
    }
    match first_name {
        Some(k) => StaticMatch::Name(k),
        None => StaticMatch::None,
    }
}

fn bytes_eq(a: &[u8], b: &[u8]) -> (r: bool)
    ensures
        r == (a@ == b@),
{
    if a.len() != b.len() {
        return false;
    }
    let mut k = 0;
    while k < a.len()
        invariant
            k <= a.len(),
            a.len() == b.len(),
            forall|m: int| 0 <= m < k ==> a@[m] == b@[m],
        decreases a.len() - k,
    {
        if a[k] != b[k] {
            return false;
        }
        k += 1;
    }
    assert(a@ =~= b@);
    true
}

} // verus!
'''


def gen_static(rows):
    s = HEADER.format(src="crates/h3/rfc/rfc9204-appendix-a.txt")
    s += '''//! QPACK static table (RFC 9204 Appendix A).
use vstd::prelude::*;

verus! {

pub const STATIC_TABLE_LEN: u64 = 99;

#[derive(Debug, PartialEq, Eq)]
pub enum StaticMatch {
    Exact(u64),
    Name(u64),
    None,
}

//= https://www.rfc-editor.org/rfc/rfc9204#appendix-A
//# This table was generated by analyzing actual Internet traffic in 2018
//# and including the most common header fields, after filtering out some
//# unsupported and non-standard values.
pub open spec fn spec_static_entry(i: nat) -> Option<(Seq<u8>, Seq<u8>)> {
'''
    for i, n, v in rows:
        s += f"    {'if' if i == 0 else '} else if'} i == {i} {{ // {n!r} {v!r}\n        Some(({seq(n)}, {seq(v)}))\n"
    s += '''    } else {
        None
    }
}

pub fn static_entry(i: u64) -> (r: Option<(&'static [u8], &'static [u8])>)
    ensures
        match r {
            Some((n, v)) => i < STATIC_TABLE_LEN && spec_static_entry(i as nat) == Some((n@, v@)),
            None => i >= STATIC_TABLE_LEN && spec_static_entry(i as nat) is None,
        },
{
    match i {
'''
    for i, n, v in rows:
        s += f"        {i} => Some(({arr(n)}, {arr(v)})),\n"
    s += "        _ => None,\n    }\n}\n"
    return s + STATIC_TAIL


def gen_huff(rows):
    s = HEADER.format(src="crates/h3/rfc/rfc7541-appendix-b.txt")
    s += '''//! HPACK/QPACK Huffman code (RFC 7541 Appendix B; RFC 9204 §4.1.2 reuses it unchanged).
use vstd::prelude::*;

verus! {

/// `(code, len)` for sym 0..=255 and 256 = EOS; code is LSB-aligned as in the RFC's hex column.
/// Out of range yields `(0, 0)`.
pub open spec fn spec_huff_code(sym: nat) -> (u32, nat) {
'''
    for i in range(257):
        h, l = rows[i]
        s += f"    {'if' if i == 0 else '} else if'} sym == {i} {{\n        (0x{h:x}u32, {l}nat)\n"
    s += '''    } else {
        (0u32, 0nat)
    }
}

pub fn huff_code(sym: u16) -> (r: (u32, u8))
    ensures
        r.0 == spec_huff_code(sym as nat).0,
        r.1 as nat == spec_huff_code(sym as nat).1,
{
    match sym {
'''
    for i in range(257):
        h, l = rows[i]
        s += f"        {i} => (0x{h:x}u32, {l}u8),\n"
    s += "        _ => (0u32, 0u8),\n    }\n}\n\n} // verus!\n"
    return s


if __name__ == "__main__":
    a = (RFC / "rfc9204-appendix-a.txt").read_text()
    b = (RFC / "rfc7541-appendix-b.txt").read_text()
    (OUT / "static_table.rs").write_text(gen_static(parse_static(a)))
    (OUT / "huffman_table.rs").write_text(gen_huff(parse_huff(b)))
